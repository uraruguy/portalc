from __future__ import annotations

import json
from pathlib import Path

import pytest

from portalc.codegen import generate_ts_client
from portalc.errors import UsageError
from portalc.pipeline import build
from portalc.workspace import Workspace

SCHEMA = {
    "title": "Invoice",
    "type": "array",
    "items": {
        "type": "object",
        "properties": {
            "number": {"type": "string"},
            "issued_on": {"type": "string", "format": "date"},
            "total_eur": {"type": "number"},
            "note": {"type": ["string", "null"]},
        },
        "required": ["number", "issued_on", "total_eur"],
    },
}


@pytest.fixture
def package(tmp_path: Path) -> Path:
    return generate_ts_client(Workspace(tmp_path), "demo-marina", SCHEMA, "list-invoices", "0.3.1")


def read(package: Path, name: str) -> str:
    return (package / name).read_text()


def test_the_package_has_everything_a_typescript_import_needs(package: Path):
    assert package.name == "portal-demo-marina"
    assert sorted(p.name for p in package.iterdir()) == [
        "README.md", "client.ts", "errors.ts", "index.ts", "package.json", "types.ts",
    ]


def test_the_row_type_is_named_after_the_schema_and_typed_per_field(package: Path):
    types = read(package, "types.ts")
    assert "export interface Invoice {" in types
    assert "  number: string;" in types
    assert "  issued_on: string;" in types
    assert "  total_eur: number;" in types
    assert "export type InvoiceList = Invoice[];" in types


def test_an_optional_column_is_optional_and_nullable(package: Path):
    assert "  note?: string | null;" in read(package, "types.ts")


def test_the_client_shells_out_to_portalc_rather_than_holding_credentials(package: Path):
    client = read(package, "client.ts")
    assert '"run", \'demo-marina\', \'list-invoices\', "--json"' in client
    assert "spawn(bin, args" in client
    for secret in ("password", "DEMO_MARINA_PASS", "cookie"):
        assert secret not in client


def test_the_client_turns_portalc_exit_codes_into_typed_errors(package: Path):
    client = read(package, "client.ts")
    assert "if (code === 6) throw new PortalDriftError" in client
    assert "if (code === 3) throw new PortalAuthError" in client
    errors = read(package, "errors.ts")
    assert 'readonly code = "PORTAL_DRIFT"' in errors
    assert 'readonly code = "PORTAL_AUTH"' in errors


def test_a_dashed_flow_name_becomes_one_camel_case_function(package: Path):
    assert "export async function listInvoices(" in read(package, "client.ts")
    assert 'export { listInvoices } from "./client";' in read(package, "index.ts")
    assert 'export type { Invoice, InvoiceList } from "./types";' in read(package, "index.ts")


def test_package_json_carries_the_portal_version(package: Path):
    meta = json.loads(read(package, "package.json"))
    assert meta["name"] == "@portalc/portal-demo-marina"
    assert meta["version"] == "0.3.1"
    assert meta["private"] is True
    assert meta["types"] == "./index.ts"


def test_the_readme_shows_the_call_and_says_not_to_hand_edit(package: Path):
    readme = read(package, "README.md")
    assert "import { listInvoices }" in readme
    assert "Do not edit by hand" in readme


def test_every_generated_file_says_it_is_generated(package: Path):
    for name in ("types.ts", "errors.ts", "client.ts", "index.ts"):
        assert read(package, name).startswith("/* generated by portalc")


def test_regenerating_over_an_existing_package_is_safe(tmp_path: Path, package: Path):
    again = generate_ts_client(Workspace(tmp_path), "demo-marina", SCHEMA, "list-invoices", "0.4.0")
    assert again == package
    assert json.loads(read(package, "package.json"))["version"] == "0.4.0"


# -- build() on a real compiled workspace --------------------------------


def test_build_generates_from_the_compiled_schema(compiled: Workspace):
    result = build(compiled, "demo-marina")
    pkg = Path(result["package"])
    assert pkg == compiled.root / "generated" / "ts" / "portal-demo-marina"
    assert result["flow"] == "list-invoices"
    types = (pkg / "types.ts").read_text()
    assert "  total_eur: number;" in types
    assert "  currency: string;" in types


def test_building_a_portal_with_nothing_compiled_is_a_usage_error(workspace: Path):
    with pytest.raises(UsageError) as caught:
        build(Workspace(workspace), "demo-marina")
    assert caught.value.exit_code == 2
    assert "portalc explore" in caught.value.hint
