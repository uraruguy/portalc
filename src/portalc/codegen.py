"""Generate a typed TypeScript client that shells out to `portalc run`."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from .workspace import Workspace


_TS_TYPES = {
    "string": "string",
    "number": "number",
    "integer": "number",
    "boolean": "boolean",
}


def _ts_type(prop: dict[str, Any]) -> str:
    raw = prop.get("type", "string")
    types = raw if isinstance(raw, list) else [raw]
    non_null = [t for t in types if t != "null"]
    core = _TS_TYPES.get(non_null[0] if non_null else "string", "string")
    if prop.get("format") == "date":
        core = "string"
    optional_null = "null" in types
    return f"{core} | null" if optional_null else core


def generate_ts_client(
    ws: Workspace,
    portal: str,
    schema: dict[str, Any],
    flow: str,
    version: str,
) -> Path:
    title = str(schema.get("title") or "Row")
    items = schema.get("items") or {}
    props: dict[str, Any] = items.get("properties") or {}
    required = set(items.get("required") or [])

    fields = []
    for name, prop in props.items():
        optional = "?" if name not in required else ""
        fields.append(f"  {name}{optional}: {_ts_type(prop)};")
    iface = "\n".join(fields)

    pkg = ws.generated_dir / "ts" / f"portal-{portal}"
    pkg.mkdir(parents=True, exist_ok=True)

    (pkg / "types.ts").write_text(
        f"""/* generated by portalc — do not edit */
export interface {title} {{
{iface}
}}

export type {title}List = {title}[];
"""
    )

    (pkg / "errors.ts").write_text(
        """/* generated by portalc — do not edit */
export class PortalDriftError extends Error {
  readonly code = "PORTAL_DRIFT";
  constructor(message: string, readonly findings?: unknown) {
    super(message);
    this.name = "PortalDriftError";
  }
}

export class PortalAuthError extends Error {
  readonly code = "PORTAL_AUTH";
  constructor(message: string) {
    super(message);
    this.name = "PortalAuthError";
  }
}
"""
    )

    (pkg / "client.ts").write_text(
        f"""/* generated by portalc — do not edit */
import {{ spawn }} from "node:child_process";
import {{ PortalAuthError, PortalDriftError }} from "./errors";
import type {{ {title} }} from "./types";

export interface RunOptions {{
  month?: string;
  extra?: Record<string, string>;
  cwd?: string;
  bin?: string;
}}

function collect(extra?: Record<string, string>, month?: string): string[] {{
  const sets: string[] = [];
  if (month) sets.push(`month=${{month}}`);
  for (const [k, v] of Object.entries(extra || {{}})) sets.push(`${{k}}=${{v}}`);
  return sets;
}}

export async function { _camel(flow) }(opts: RunOptions = {{}}): Promise<{title}[]> {{
  const bin = opts.bin || "portalc";
  const sets = collect(opts.extra, opts.month);
  const args = ["run", {portal!r}, {flow!r}, "--json", ...sets.flatMap((s) => ["--set", s])];
  const child = spawn(bin, args, {{ cwd: opts.cwd, stdio: ["ignore", "pipe", "pipe"] }});
  const stdout: Buffer[] = [];
  const stderr: Buffer[] = [];
  child.stdout.on("data", (c) => stdout.push(c));
  child.stderr.on("data", (c) => stderr.push(c));
  const code: number = await new Promise((resolve) => child.on("close", resolve));
  const out = Buffer.concat(stdout).toString("utf8");
  const err = Buffer.concat(stderr).toString("utf8");
  if (code === 0) {{
    return JSON.parse(out) as {title}[];
  }}
  if (code === 6) throw new PortalDriftError(err.trim() || "portal drifted", safeJson(out));
  if (code === 3) throw new PortalAuthError(err.trim() || "portal auth failed");
  throw new Error(err.trim() || `portalc run exited ${{code}}`);
}}

function safeJson(text: string): unknown {{
  try {{ return JSON.parse(text); }} catch {{ return undefined; }}
}}
"""
    )

    (pkg / "index.ts").write_text(
        f"""/* generated by portalc — do not edit */
export type {{ {title}, {title}List }} from "./types";
export {{ PortalDriftError, PortalAuthError }} from "./errors";
export {{ {_camel(flow)} }} from "./client";
"""
    )

    (pkg / "package.json").write_text(
        json_pp(
            {
                "name": f"@portalc/portal-{portal}",
                "version": version,
                "private": True,
                "type": "module",
                "main": "./index.ts",
                "types": "./index.ts",
                "description": f"Generated typed client for the {portal} portal. Run via portalc.",
            }
        )
    )
    (pkg / "README.md").write_text(
        f"""# @portalc/portal-{portal}

Generated by portalc. Do not edit by hand — change the schema and re-run `portalc build`.

```ts
import {{ {_camel(flow)} }} from "@portalc/portal-{portal}";

const rows = await {_camel(flow)}({{ month: "2026-09" }});
```

The client shells out to the `portalc` CLI so runtime stays deterministic and secret-free in git.
"""
    )
    return pkg


def _camel(flow: str) -> str:
    parts = flow.replace("-", "_").split("_")
    return parts[0] + "".join(p.title() for p in parts[1:])


def json_pp(payload: dict[str, Any]) -> str:
    import json

    return json.dumps(payload, indent=2) + "\n"
